 select exists(select 1 from public.profiles p where p.id=auth.uid() and lower(p.role)='admin' and coalesce(p.disabled,false)=false);
$$;


create or replace function public.sync_access_state() returns void language plpgsql security definer set search_path=public as $$
begin
 update public.profiles set role='user' where id=auth.uid() and lower(role)='vip' and (vip_until is null or vip_until<=now());
 update public.profiles set free_credits=100, free_reset_at=null where id=auth.uid() and free_credits=0 and free_reset_at is not null and free_reset_at<=now();
end; $$;


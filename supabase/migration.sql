create or replace function public.consume_tool_v2(p_tool_id text, p_cost integer default 10) returns jsonb language plpgsql security definer set search_path=public as $$
declare p public.profiles%rowtype; c integer; f integer; r integer;
begin
 select * into p from public.profiles where id=auth.uid() for update;
 if p.id is null then raise exception 'SESSION_EXPIRED'; end if;
 if p.disabled then raise exception 'ACCOUNT_DISABLED'; end if;
 if lower(p.role)='vip' and (p.vip_until is null or p.vip_until<=now()) then p.role:='user'; update public.profiles set role='user' where id=p.id; end if;
 if lower(p.role)='admin' then c:=0;
 elsif p.vip_until is not null and p.vip_until>now() then c:=0;
 else
   if p.free_credits=0 and p.free_reset_at is not null and p.free_reset_at<=now() then p.free_credits:=100; p.free_reset_at:=null; end if;
   if p.free_credits >= p_cost then f:=p_cost; r:=0; elsif p.free_credits>0 then f:=p.free_credits; r:=p_cost-p.free_credits; else f:=0; r:=p_cost; end if;
   if p.purchased_credits < r then raise exception 'INSUFFICIENT_CREDITS'; end if;
   p.free_credits:=p.free_credits-f; p.purchased_credits:=p.purchased_credits-r;
   if p.free_credits=0 and p.free_reset_at is null then p.free_reset_at:=now()+interval '1 hour'; end if;
   c:=p_cost;
 end if;
 update public.profiles set free_credits=p.free_credits,purchased_credits=p.purchased_credits,free_reset_at=p.free_reset_at,tool_uses=coalesce(p.tool_uses,0)+1,last_active=now() where id=p.id;
 insert into public.tool_usage(user_id,tool_id,credits_cost) values(auth.uid(),p_tool_id,c);
 return jsonb_build_object('ok',true,'credits_cost',c,'free_credits',p.free_credits,'purchased_credits',p.purchased_credits,'vip_until',p.vip_until,'role',p.role);
exception when others then
 if sqlerrm in ('INSUFFICIENT_CREDITS','ACCOUNT_DISABLED','SESSION_EXPIRED') then raise; else raise; end if;
end; $$;


create or replace function public.create_order(p_product text,p_price integer,p_credits integer default 0,p_vip_days integer default 0) returns public.orders language plpgsql security definer set search_path=public as $$
declare u public.profiles%rowtype; o public.orders;
begin select * into u from profiles where id=auth.uid(); if u.id is null then raise exception 'SESSION_EXPIRED'; end if;
insert into orders(user_id,username,product,price,credits,vip_days) values(auth.uid(),u.username,p_product,p_price,p_credits,p_vip_days) returning * into o; return o; end; $$;

create or replace function public.complete_order(p_order_id text) returns public.orders language plpgsql security definer set search_path=public as $$
declare o public.orders; v public.profiles%rowtype;
begin
 if not public.is_admin() then raise exception 'FORBIDDEN'; end if;
 select * into o from orders where id=p_order_id for update;
 if o.id is null then raise exception 'ORDER_NOT_FOUND'; end if;
 if o.status='COMPLETED' then return o; end if;
 if o.status<>'PENDING' then raise exception 'ORDER_NOT_PENDING'; end if;
 select * into v from profiles where id=o.user_id for update;
 update profiles set purchased_credits=coalesce(purchased_credits,0)+o.credits, vip_until=case when o.vip_days>0 then greatest(coalesce(vip_until,now()),now())+make_interval(days=>o.vip_days) else vip_until end, role=case when o.vip_days>0 then 'vip' else role end where id=o.user_id;
 update orders set status='COMPLETED',completed_at=now() where id=o.id returning * into o;
 insert into admin_activity_logs(admin_id,admin_username,action,target_type,target_id,details) select auth.uid(),username,'completed order','order',o.id,jsonb_build_object('credits',o.credits,'vip_days',o.vip_days) from profiles where id=auth.uid();
 return o;
end; $$;

create or replace function public.adjust_purchased_credits(p_user_id uuid,p_delta integer) returns public.profiles language plpgsql security definer set search_path=public as $$
declare p public.profiles;
begin if not public.is_admin() then raise exception 'FORBIDDEN'; end if; update profiles set purchased_credits=greatest(0,coalesce(purchased_credits,0)+p_delta) where id=p_user_id returning * into p; return p; end; $$;
create or replace function public.grant_vip(p_user_id uuid,p_days integer default 30) returns public.profiles language plpgsql security definer set search_path=public as $$
declare p public.profiles;
begin if not public.is_admin() then raise exception 'FORBIDDEN'; end if; update profiles set vip_until=greatest(coalesce(vip_until,now()),now())+make_interval(days=>p_days),role=case when lower(role)<>'admin' then 'vip' else role end where id=p_user_id returning * into p; return p; end; $$;
create or replace function public.revoke_vip(p_user_id uuid) returns public.profiles language plpgsql security definer set search_path=public as $$
declare p public.profiles;
begin if not public.is_admin() then raise exception 'FORBIDDEN'; end if; update profiles set vip_until=null,role=case when lower(role)='vip' then 'user' else role end where id=p_user_id returning * into p; return p; end; $$;

